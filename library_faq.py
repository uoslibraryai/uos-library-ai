"""UOS Library AI - library_faq.py

100 Rules & Regulations FAQs for the Wazir Agha Library, University of
Sargodha, built ONLY from official sources checked on 23 November 2026:

  * SRC_COC  - Wazir Agha Library Code of Conduct, approved by the Vice
    Chancellor (University of Sargodha Registrar notification dated
    04-09-2024, on the recommendation of the Chief Librarian).
  * SRC_FORM - Official UOS "Form for the Book Price Payment"
    (library.su.edu.pk) - the ONLY source used for lost-book price
    multipliers.
  * SRC_INFO - Official Information Services page (library.su.edu.pk).

Rules kept from the rest of the project (decision D1):
  * No invented policies: borrowing limits, loan periods, membership
    fees/process and exact per-violation fine amounts are NOT published
    in these sources, so they are NOT stated here. Where a question has
    no published answer, the FAQ says so and gives the library contact.
  * The lost-book form lists multipliers for books up to 5 years (2x),
    up to 10 years (3x), up to 13 years (4x) and 20 years and above
    (5x). The 13-20 year gap is NOT specified in the form and is NOT
    filled in here.
  * The Code of Conduct says fines may be imposed up to Rs. 5,000 for
    listed violations, but the per-violation amounts in the copy
    checked could not be read reliably, so no exact amount per
    violation is stated.
  * The chatbot cannot itself reserve, renew, borrow or take payments;
    answers only explain the library's own process.

Matching: deliberately strict, two channels. (1) Phrase channel: the
question must contain a distinctive multi-word phrase from an FAQ's
match list (or a long distinctive word). (2) Canonical-question
channel: at least 80% of an FAQ's own question words (stopwords
removed, minimum 3 content words) must appear in the user's text -
this catches natural rephrasings of the 100 questions themselves.
Generic single words (book, phone, fine...) never match alone, and
if two FAQs score equally the matcher returns None, so unrelated
questions fall through to the normal routes instead of getting a
wrong policy answer.
"""

