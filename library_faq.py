# Extra Roman Urdu words used only to pick the answer language when a
# question matched an FAQ but app.py's own detector missed it.
_FAQ_URDU_WORDS = {
    "kya", "main", "mujhe", "sakta", "sakti", "kar", "ka", "ki", "ke",
    "mein", "par", "hai", "hain", "hoga", "hogi", "chahiye", "lazmi",
    "kahan", "kaise", "kitne", "kitna", "agar", "mera", "meri", "apna",
    "apni", "saman", "kitab", "khana", "pani", "jayega", "milegi",
    "rakhun", "layein", "bhool", "ghum", "kho", "wapas", "bina",
}


def _normalize(text):
    text = text.lower().replace("’", "'")
    text = re.sub(r"[^a-z0-9 ]+", " ", text)
    return re.sub(r"\s+", " ", text).strip()


def _phrase_score(phrase):
    return 10 * len(phrase.split()) + len(phrase)


# Words that carry no topic meaning in a question - removed before the
# canonical-question containment check.
_STOPWORDS = {
    "do", "does", "did", "i", "you", "we", "he", "she", "it", "to",
    "the", "a", "an", "of", "in", "on", "at", "for", "from", "with",
    "my", "me", "your", "can", "could", "should", "would", "is", "are",
    "am", "was", "were", "be", "been", "if", "or", "and", "but", "so",
    "what", "when", "where", "who", "how", "why", "kya", "main",
    "mujhe", "mujh", "hai", "hain", "hun", "ho", "sakta", "sakti",
    "kar", "ka", "ki", "ke", "ko", "se", "par", "mein", "ya", "jo",
    "woh", "yeh", "bhi", "agar", "to", "na", "nahi", "mera", "meri",
}


def _content_words(text):
    return {w for w in _normalize(text).split() if w not in _STOPWORDS}


for _f in FAQS:
    _f["_q_words"] = (_content_words(_f["q_en"]), _content_words(_f["q_ru"]))


def find_faq(text):
    """Return the single best-matching FAQ dict, or None.

    Strict on purpose: a match needs a distinctive phrase worth at
    least 20 points (a two-word phrase, or a long distinctive word),
    or an 80%+ containment of one of the FAQ's own canonical
    questions. The best FAQ must beat the runner-up outright - a tie
    returns None so the question falls through to the normal routes.
    """
    norm = " " + _normalize(text) + " "
    user_words = set(_normalize(text).split())
    best, best_score, second_score = None, 0, 0
    for faq in FAQS:
        score = 0
        for phrase in faq["match"]:
            p = _normalize(phrase)
            if (" " + p + " ") in norm or norm.strip() == p:
                score += _phrase_score(p)
        best_containment = 0.0
        for q_words in faq["_q_words"]:
            if len(q_words) >= 3:
                # A number in a canonical question is its distinguishing
                # feature (e.g. the lost-book year bands): if the user's
                # text does not contain that same number, this question
                # cannot be the match.
                q_digits = {w for w in q_words if w.isdigit()}
                if q_digits and not q_digits <= user_words:
                    continue
                containment = len(q_words & user_words) / len(q_words)
                best_containment = max(best_containment, containment)
        if best_containment >= 0.8:
            score += 500 + round(best_containment * 100)
        if score > best_score:
            best, second_score, best_score = faq, best_score, score
        elif score > second_score:
            second_score = score
    if best is not None and best_score >= 20 and best_score > second_score:
        return best
    return None


def faq_answer(text, roman_urdu=False):
    """Full FAQ answer (with source link) for a question, or None.

    The answer language follows the caller flag, or the FAQ module's
    own Roman Urdu detection when the flag is False."""
    faq = find_faq(text)
    if faq is None:
        return None
    if not roman_urdu:
        words = set(_normalize(text).split())
        roman_urdu = len(words & _FAQ_URDU_WORDS) >= 2
    body = faq["a_ru"] if roman_urdu else faq["a_en"]
    return f"{body}\n\nSource: {faq['source']}"
